#!/usr/bin/env python3
"""Builds the lookup tables for text written in place as Japanese/English pairs.

lib/l10n/inline/<locale>.json maps each English text (templates keep {0}, {1}) to its
translation. This writes lib/l10n/inline_strings.g.dart for Flutter and
android/app/src/main/resources/moe/n4tsu/dextop/l10n/inline_<locale>.json for Kotlin
(InlineStrings). With --check it lists the English texts in the code (tool/inline_strings.py)
that a locale has no translation for, and fails if there are any.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib' / 'l10n' / 'inline'
DART = ROOT / 'lib' / 'l10n' / 'inline_strings.g.dart'
RESOURCES = ROOT / 'android' / 'app' / 'src' / 'main' / 'resources' / 'moe' / 'n4tsu' / 'dextop' / 'l10n'
LOCALES = ['ko', 'zh', 'ru', 'pt', 'pt_BR']


def load():
    return {locale: json.loads((SOURCE / ('%s.json' % locale)).read_text(encoding='utf-8')) for locale in LOCALES}


def dart_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def generate():
    tables = load()
    lines = ['// Generated by tool/generate_inline_strings.py from lib/l10n/inline/*.json. Do not edit.',
             '// ignore_for_file: lines_longer_than_80_chars', '',
             'const Map<String, Map<String, String>> inlineStrings = {']
    for locale in LOCALES:
        lines.append("  '%s': {" % locale)
        for en, text in sorted(tables[locale].items()):
            lines.append('    %s: %s,' % (dart_string(en), dart_string(text)))
        lines.append('  },')
    lines.append('};')
    DART.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    RESOURCES.mkdir(parents=True, exist_ok=True)
    for locale in LOCALES:
        (RESOURCES / ('inline_%s.json' % locale)).write_text(
            json.dumps(tables[locale], ensure_ascii=False, sort_keys=True, indent=0), encoding='utf-8', newline='\n')


def check():
    tables = load()
    out = subprocess.run([sys.executable, str(ROOT / 'tool' / 'inline_strings.py'), '--list'],
                         capture_output=True, text=True, encoding='utf-8', check=True).stdout
    texts = [json.loads(line) for line in out.splitlines() if line.strip()]
    missing = {locale: [t for t in texts if t not in tables[locale]] for locale in LOCALES}
    unused = sorted(set().union(*(tables[l].keys() for l in LOCALES)) - set(texts))
    for locale, items in missing.items():
        for t in items:
            print('missing %s: %s' % (locale, json.dumps(t, ensure_ascii=False)))
    for t in unused:
        print('unused: %s' % json.dumps(t, ensure_ascii=False))
    return not any(missing.values())


if __name__ == '__main__':
    if '--check' in sys.argv:
        sys.exit(0 if check() else 1)
    generate()
