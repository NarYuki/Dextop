#!/usr/bin/env python3
"""Generate keyed UI catalogs for Flutter and the Android applications.

The source of truth is lib/l10n/inline/<locale>.json. Display text is not
embedded at call sites. Numeric placeholders are substituted after lookup.
"""

import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'lib/l10n/inline'
DART = ROOT / 'lib/l10n/inline_strings.g.dart'
LOCALES = ['ja', 'en', 'ko', 'zh', 'ru', 'pt', 'pt_BR']
RESOURCE_ROOTS = [ROOT / f'android/{module}/src/main/resources/moe/n4tsu/dextop/l10n'
                  for module in ['app', 'cardex']]


def load():
    return {locale: json.loads((SOURCE / f'{locale}.json').read_text(encoding='utf-8'))
            for locale in LOCALES}


def dart_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n').replace('\r', '\\r') + "'"


def properties_string(text):
    return (text.replace('\\', '\\\\').replace('\n', '\\n').replace('\r', '\\r')
            .replace('\t', '\\t').replace('=', '\\=').replace(':', '\\:')
            .replace(' ', '\\ '))


def outputs(tables):
    lines = ['// Generated by tool/generate_inline_strings.py. Do not edit.',
             '// ignore_for_file: lines_longer_than_80_chars', '// dart format off', '',
             'const Map<String, Map<String, String>> inlineStrings = {']
    for locale, values in tables.items():
        lines.append(f"  '{locale}': {{")
        lines.extend(f'    {dart_string(key)}: {dart_string(text)},' for key, text in sorted(values.items()))
        lines.append('  },')
    lines.extend(['};', ''])
    result = {DART: '\n'.join(lines)}
    companion_source = '\n'.join(p.read_text(encoding='utf-8')
                                 for p in (ROOT / 'android/cardex/src/main/kotlin').rglob('*.kt'))
    companion_keys = set(re.findall(r'"(ui[A-Za-z0-9]+)"', companion_source))
    for directory in RESOURCE_ROOTS:
        for locale, values in tables.items():
            selected = values if '/app/' in directory.as_posix() else {key: values[key] for key in sorted(companion_keys) if key in values}
            result[directory / f'inline_{locale}.properties'] = ''.join(
                f'{key}={properties_string(text)}\n' for key, text in sorted(selected.items()))
    resource_keys = json.loads((ROOT / 'tool/companion_resource_keys.json').read_text(encoding='utf-8'))
    resource_keys.update(companion_parking_name='uiDextopParking', companion_driving_name='uiDextopDriving')
    directories = {'en': 'values', 'ja': 'values-ja', 'ko': 'values-ko', 'zh': 'values-zh',
                   'ru': 'values-ru', 'pt': 'values-pt', 'pt_BR': 'values-pt-rBR'}
    for locale, directory in directories.items():
        lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated from the shared UI catalogs. -->', '<resources>']
        lines.extend(f'    <string name="{name}" formatted="false">"{escape(tables[locale][key]).replace(chr(34), chr(92) + chr(34))}"</string>'
                     for name, key in resource_keys.items())
        lines.extend(['</resources>', ''])
        result[ROOT / f'android/cardex/src/main/res/{directory}/strings.xml'] = '\n'.join(lines)
    guest_keys = ('uiAndroidCalendar', 'uiCalendarNoTitle', 'uiICalendar')
    guest = {locale: {key: table[key] for key in guest_keys} for locale, table in tables.items()}
    result[ROOT / 'android/app/src/main/resources/moe/n4tsu/dextop/linux/dextop-ui.json'] = json.dumps(guest, ensure_ascii=False, indent=2) + '\n'
    return result


def check():
    tables = load()
    valid = True
    reference = tables['en']
    for locale, table in tables.items():
        if table.keys() != reference.keys():
            print(f'{locale}: catalog keys do not match English')
            valid = False
        for key, text in table.items():
            expected = set(re.findall(r'\{\d+\}', reference.get(key, '')))
            if not text or set(re.findall(r'\{\d+\}', text)) != expected:
                print(f'{locale}: empty translation or invalid placeholders: {key}')
                valid = False
    for path, contents in outputs(tables).items():
        if not path.exists() or path.read_text(encoding='utf-8') != contents:
            print(f'{path.relative_to(ROOT)}: generated translations are stale')
            valid = False
    return valid


def generate():
    for path, contents in outputs(load()).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    if '--check' in sys.argv:
        sys.exit(0 if check() else 1)
    generate()
